import test from 'node:test'
import assert from 'node:assert/strict'
import express from 'express'
process.env.NODE_ENV = 'test'
const { default: db } = await import('../db/init.js')
const { auth } = await import('../auth/betterAuth.js')
const { createRequireAuth } = await import('../middleware/authPolicy.js')
const { createUserRouter } = await import('./user.js')
const app = express(); app.use(express.json({ limit: '2mb' }))
app.use('/user', createUserRouter({ database: db, authMiddleware: createRequireAuth({ database: db, auth }) }))
let server, base
const signup = async () => auth.api.signUpEmail({ body: { email: `account-${crypto.randomUUID()}@example.test`, password: 'original-password-123', name: 'Original', policyAcceptance: { termsAccepted: true, privacyAcknowledged: true, termsVersion: '2026-10-19', privacyVersion: '2026-10-19', locale: 'en' } } })
const request = async (token, path, method = 'GET', body) => {
  const response = await fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) })
  return { status: response.status, data: await response.json() }
}
test.before(async () => { server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r)); base = `http://127.0.0.1:${server.address().port}/user` })
test.after(() => server.close())
test('profile persists native name, extended fields, revisions and isolates owners', async () => {
  const a = await signup(), b = await signup()
  const initial = await request(a.token, '/profile'); assert.equal(initial.data.account.name, 'Original')
  const saved = await request(a.token, '/profile', 'PATCH', { revision: 0, patch: { name: 'New name', bio: 'About me', avatar: null } })
  assert.equal(saved.status, 200); assert.equal(saved.data.account.name, 'New name'); assert.equal(saved.data.account.revision, 1)
  assert.equal(db.prepare('SELECT name FROM user WHERE id=?').get(a.user.id).name, 'New name')
  assert.equal((await request(a.token, '/profile')).data.account.profile.bio, 'About me')
  assert.equal((await request(b.token, '/profile')).data.account.profile.bio, undefined)
  assert.equal((await request(a.token, '/profile', 'PATCH', { revision: 0, patch: { name: 'Stale' } })).status, 409)
  assert.equal((await request(a.token, '/profile', 'PATCH', { revision: 1, patch: { isAdmin: true } })).status, 400)
  assert.equal((await request(a.token, '/profile', 'PATCH', { revision: 1, patch: { avatar: 'javascript:alert(1)' } })).status, 400)
})
test('session listing hides credentials and owner-scoped revoke protects other users', async () => {
  const a = await signup(), b = await signup()
  const another = await auth.api.signInEmail({ body: { email: a.user.email, password: 'original-password-123' } })
  const details = await request(a.token, '/account'); assert.equal(details.status, 200)
  assert.deepEqual(details.data.providers, ['credential']); assert.equal(details.data.hasPassword, true)
  assert.ok(details.data.sessions.some(s => s.current)); assert.ok(details.data.sessions.every(s => !('token' in s)))
  const bSession = db.prepare('SELECT id FROM session WHERE token=?').get(b.token)
  assert.equal((await request(a.token, `/sessions/${bSession.id}/revoke`, 'POST', {})).status, 404)
  const other = db.prepare('SELECT id FROM session WHERE token=?').get(another.token)
  assert.equal((await request(a.token, `/sessions/${other.id}/revoke`, 'POST', {})).status, 200)
  assert.equal((await request(another.token, '/profile')).status, 401)
})
test('password change verifies old password and revokes other sessions', async () => {
  const a = await signup(); const second = await auth.api.signInEmail({ body: { email: a.user.email, password: 'original-password-123' } })
  assert.equal((await request(a.token, '/password', 'POST', { currentPassword: 'wrong', newPassword: 'updated-password-456' })).status, 400)
  assert.equal((await request(a.token, '/password', 'POST', { currentPassword: 'original-password-123', newPassword: 'updated-password-456' })).status, 200)
  assert.equal((await request(second.token, '/profile')).status, 401)
  const login = await auth.api.signInEmail({ body: { email: a.user.email, password: 'updated-password-456' } }); assert.ok(login.token)
})
test('deletion requires proof, disables server account and invalidates sessions', async () => {
  const a = await signup(); await request(a.token, '/profile')
  assert.equal((await request(a.token, '/account/deletion', 'POST', { confirmEmail: a.user.email, password: 'wrong' })).status, 400)
  const result = await request(a.token, '/account/deletion', 'POST', { confirmEmail: a.user.email, password: 'original-password-123' })
  assert.equal(result.status, 200); assert.ok(result.data.deletionEligibleAt > Date.now())
  assert.equal(db.prepare('SELECT status FROM users WHERE auth_user_id=?').get(a.user.id).status, 'deletion_pending')
  assert.equal((await request(a.token, '/profile')).status, 401)
})
test('revoke others keeps current session and unrelated accounts active', async () => {
  const a = await signup(), b = await signup()
  const other = await auth.api.signInEmail({ body: { email: a.user.email, password: 'original-password-123' } })
  const current = db.prepare('SELECT id FROM session WHERE token=?').get(a.token)
  assert.equal((await request(a.token, `/sessions/${current.id}/revoke`, 'POST', {})).status, 400)
  assert.equal((await request(a.token, '/sessions/revoke-others', 'POST', {})).status, 200)
  assert.equal((await request(a.token, '/account')).status, 200)
  assert.equal((await request(other.token, '/account')).status, 401)
  assert.equal((await request(b.token, '/account')).status, 200)
})
test('OAuth account deletion requires a fresh sign-in and matching email', async () => {
  const a = await signup(); await request(a.token, '/profile')
  db.prepare("UPDATE account SET providerId='google',password=NULL WHERE userId=?").run(a.user.id)
  db.prepare('UPDATE session SET createdAt=? WHERE token=?').run(new Date(Date.now()-10*60_000).toISOString(), a.token)
  assert.equal((await request(a.token, '/account/deletion', 'POST', { confirmEmail: 'other@example.test' })).status, 400)
  assert.equal((await request(a.token, '/account/deletion', 'POST', { confirmEmail: a.user.email })).status, 403)
  assert.equal((await request(a.token, '/account')).status, 200)
  db.prepare('UPDATE session SET createdAt=? WHERE token=?').run(new Date().toISOString(), a.token)
  assert.equal((await request(a.token, '/account/deletion', 'POST', { confirmEmail: a.user.email })).status, 200)
})
test('rate-limits repeated password guesses and rejects invalid fields', async () => {
  const a = await signup()
  for (const patch of [{ constructor: 'bad' }, { name: '  ' }, { bio: 'x'.repeat(1001) }]) assert.equal((await request(a.token, '/profile', 'PATCH', { revision: 0, patch })).status, 400)
  for (let i=0;i<8;i++) assert.equal((await request(a.token, '/password', 'POST', { currentPassword: 'wrong', newPassword: 'new-password-123' })).status, 400)
  assert.equal((await request(a.token, '/password', 'POST', { currentPassword: 'wrong', newPassword: 'new-password-123' })).status, 429)
})
test('integration tokens cannot manage identity, and deletion revokes them', async () => {
  const { ensureIntegrationTokenTable, createIntegrationToken } = await import('../auth/integrationTokens.js')
  ensureIntegrationTokenTable(db)
  const a = await signup(); await request(a.token, '/profile')
  const integration = createIntegrationToken(db, a.user.id, 'test integration')
  assert.equal((await request(integration.token, '/profile')).status, 200)
  assert.equal((await request(integration.token, '/account')).status, 403)
  assert.equal((await request(integration.token, '/profile', 'PATCH', { revision: 0, patch: { name: 'Forbidden' } })).status, 403)
  assert.equal((await request(a.token, '/account/deletion', 'POST', { confirmEmail: a.user.email, password: 'original-password-123' })).status, 200)
  assert.equal((await request(integration.token, '/profile')).status, 401)
})
test('legacy account confirmation is explicit, owner scoped, validated and append-only', async () => {
  const a = await signup(), b = await signup()
  db.prepare('DELETE FROM policy_acceptances WHERE auth_user_id IN (?,?)').run(a.user.id, b.user.id)
  assert.equal((await request(a.token, '/policy')).data.acceptance, null)
  assert.equal((await request(a.token, '/policy', 'POST', { termsAccepted: false })).status, 400)
  const body = { termsAccepted: true, privacyAcknowledged: true, termsVersion: '2026-10-19', privacyVersion: '2026-10-19', locale: 'zh', authUserId: b.user.id, acceptedAt: 1 }
  const saved = await request(a.token, '/policy', 'POST', body)
  assert.equal(saved.status, 200); assert.equal(saved.data.acceptance.source, 'account-confirmation'); assert.ok(saved.data.acceptance.acceptedAt > 1)
  assert.equal((await request(b.token, '/policy')).data.acceptance, null)
  const again = await request(a.token, '/policy', 'POST', { ...body, locale: 'en' })
  assert.deepEqual(again.data.acceptance, saved.data.acceptance)
})
