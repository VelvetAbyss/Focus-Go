let apiProcess: ChildProcess, webProcess: ChildProcess, apiBase: string
const waitForPort = (child: ChildProcess) => new Promise<number>((done, reject) => {
  let output = ''
  const timeout = setTimeout(() => reject(new Error(`Account API timeout: ${output}`)), 15_000)
  child.stdout?.on('data', chunk => { output += String(chunk); const match = output.match(/\{"port":(\d+)\}/); if (match) { clearTimeout(timeout); done(Number(match[1])) } })
  child.stderr?.on('data', chunk => { output += String(chunk) })
  child.on('exit', code => { clearTimeout(timeout); reject(new Error(`Account API exit ${code}: ${output}`)) })
})
test.beforeAll(async () => {
  apiProcess = spawn(process.execPath, [resolve('focus-go-api/test/fixtures/account-browser-server.js')], { cwd: resolve('focus-go-api') })
  apiBase = `http://127.0.0.1:${await waitForPort(apiProcess)}`
  webProcess = spawn(process.execPath, [resolve('../../node_modules/vite/bin/vite.js'), '--host', '127.0.0.1', '--port', '5186', '--strictPort'], { cwd: process.cwd(), env: { ...process.env, VITE_API_BASE: apiBase, VITE_AUTH_API_BASE: `${apiBase}/api/auth` } })
  for (let attempt = 0; attempt < 100; attempt++) {
    try { if ((await fetch('http://127.0.0.1:5186/')).ok) return } catch { /* wait for Vite */ }
    if (webProcess.exitCode !== null) throw new Error('Account Vite exited')
    await new Promise(done => setTimeout(done, 200))
  }
  throw new Error('Account Vite timed out')
})
test.afterAll(() => { webProcess?.kill('SIGTERM'); apiProcess?.kill('SIGTERM') })
const signIn = async (path: string, body: Record<string, string>) => {
  const response = await fetch(`${apiBase}/api/auth/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'http://127.0.0.1:5186' }, body: JSON.stringify(path === 'sign-up/email' ? { ...body, policyAcceptance: { termsAccepted: true, privacyAcknowledged: true, termsVersion: '2026-10-19', privacyVersion: '2026-10-19', locale: 'en' } } : body) })
  expect(response.ok, await response.text()).toBe(true)
  const cookie = response.headers.getSetCookie().find(value => value.startsWith('better-auth.session_token='))!
  expect(cookie).toBeTruthy()
  return { name: 'better-auth.session_token', value: cookie.split(';')[0].split('=').slice(1).join('='), url: apiBase }
}
