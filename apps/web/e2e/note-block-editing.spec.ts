import { expect, test, type Page } from '@playwright/test'

// Keep local editor regressions independent of the live authentication service.
test.beforeEach(async ({ page }) => {
  await page.route('**/api/auth/get-session', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: 'null' }))
})
const setup = async (page: Page, contentMd = 'First paragraph\n\nSecond paragraph\n\nThird paragraph') => {
  await page.goto('/note')
  await expect(page.locator('.note-page-shell')).toBeVisible({ timeout: 15000 })
  const id = await page.evaluate(async (contentMd) => {
    const { notesRepo } = await import('/src/data/repositories/notesRepo.ts')
    return (await notesRepo.create({ title: 'Block editing', contentMd, tags: [], collection: 'all-notes' })).id
  }, contentMd)
  await page.goto(`/note?note=${id}`)
  await expect(page.locator('.ProseMirror')).toContainText('First', { timeout: 15000 })
  return page.locator('.ProseMirror')
}

test('selection menu applies formatting and conversion in place, retaining text and undo', async ({ page }) => {
  const editor = await setup(page)
  await editor.locator('p').first().click()
  await editor.locator('p').first().evaluate((element) => {
    const range = document.createRange()
    range.selectNodeContents(element)
    const selection = window.getSelection()!
    selection.removeAllRanges()
    selection.addRange(range)
  })
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('First paragraph')
  const menu = page.getByRole('toolbar', { name: 'Text formatting' })
  await expect(menu).toBeVisible()
  await menu.getByRole('button', { name: /Bold/ }).click()
  await expect(editor.locator('strong')).toHaveText('First paragraph')
  await menu.getByLabel('Turn into').selectOption('heading2')
  await expect(editor.locator('h2')).toHaveText('First paragraph')
  await expect(editor.locator('h2 strong')).toHaveText('First paragraph')
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('h2')).toHaveCount(0)
  await expect(editor.locator('p strong')).toHaveText('First paragraph')
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('strong')).toHaveCount(0)
})

test('slash heading and checklist conversions undo as individual actions', async ({ page }) => {
  const editor = await setup(page)
  await editor.click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.press('Enter')
  await page.keyboard.type('/h2')
  await page.keyboard.press('Enter')
  await expect(editor.locator('h2')).toHaveCount(1)
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor).toContainText('/h2')
  await expect(editor.locator('h2')).toHaveCount(0)
  await page.keyboard.press('ControlOrMeta+Shift+Z')
  await page.keyboard.type('Next step')
  await editor.locator('h2').hover()
  await page.getByRole('button', { name: 'Block actions — drag to move' }).click()
  await page.getByRole('menuitem', { name: 'Checklist', exact: true }).click()
  await expect(editor.locator('ul[data-type="taskList"]')).toContainText('Next step')
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('h2')).toHaveText('Next step')
})

test('block menu and keyboard move content with one-step undo and redo', async ({ page }) => {
  const editor = await setup(page)
  await editor.locator('p').nth(1).hover()
  await page.getByRole('button', { name: 'Block actions — drag to move' }).click()
  const menu = page.getByRole('menu', { name: 'Block actions — drag to move' })
  await expect(menu.getByRole('menuitem', { name: 'Move up' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(editor.locator('p').first()).toHaveText('Second paragraph')
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('p').first()).toHaveText('First paragraph')
  await page.keyboard.press('ControlOrMeta+Shift+Z')
  await expect(editor.locator('p').first()).toHaveText('Second paragraph')
  await page.keyboard.press('Alt+Shift+ArrowDown')
  await expect(editor.locator('p').first()).toHaveText('First paragraph')
})

test('native handle drag displays a destination and moves once without duplicating content', async ({ page }) => {
  const editor = await setup(page)
  await editor.locator('p').nth(1).hover()
  const handle = page.getByRole('button', { name: 'Block actions — drag to move' })
  const source = (await handle.boundingBox())!
  const target = (await editor.locator('p').first().boundingBox())!
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + 80, target.y + 2, { steps: 12 })
  await expect(page.locator('.note-block-drop')).toBeVisible()
  await page.screenshot({ path: '../../artifacts/notion-editing-2026-10-14/block-drop.png' })
  await page.mouse.up()
  await expect(editor.locator('p').first()).toHaveText('Second paragraph')
  await expect(editor.locator('p')).toHaveCount(3)
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('p').first()).toHaveText('First paragraph')
})

test('390px Chinese selection tools remain inside the viewport and block menu Escape restores focus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => localStorage.setItem('workbench.ui.language', 'zh'))
  const editor = await setup(page)
  await editor.locator('p').first().click()
  await editor.locator('p').first().evaluate((element) => {
    const range = document.createRange()
    range.selectNodeContents(element)
    const selection = window.getSelection()!
    selection.removeAllRanges()
    selection.addRange(range)
  })
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('First paragraph')
  const menu = page.getByRole('toolbar', { name: '文字格式' })
  await expect(menu).toBeVisible()
  const rect = (await menu.boundingBox())!
  expect(rect.x).toBeGreaterThanOrEqual(0)
  expect(rect.x + rect.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '../../artifacts/notion-editing-2026-10-14/selection-zh-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await page.keyboard.press('ArrowRight')
  await editor.locator('p').nth(1).hover()
  await page.getByRole('button', { name: '块操作 — 拖动可移动' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu', { name: '块操作 — 拖动可移动' })).toHaveCount(0)
  await expect(editor).toBeFocused()
})

test('block menu at the end of a long mobile note stays visible and respects the last-block boundary', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const editor = await setup(page, Array.from({ length: 30 }, (_, i) => `First ${i + 1} paragraph`).join('\n\n'))
  const last = editor.locator('p').last()
  await last.scrollIntoViewIfNeeded()
  await last.click()
  await last.hover()
  await page.getByRole('button', { name: 'Block actions — drag to move' }).click()
  const menu = page.getByRole('menu', { name: 'Block actions — drag to move' })
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Move down' })).toBeDisabled()
  const rect = (await menu.boundingBox())!
  expect(rect.x).toBeGreaterThanOrEqual(0)
  expect(rect.y).toBeGreaterThanOrEqual(0)
  expect(rect.x + rect.width).toBeLessThanOrEqual(390)
  expect(rect.y + rect.height).toBeLessThanOrEqual(844)
  await page.screenshot({ path: '../../artifacts/notion-editing-2026-10-14/block-menu-mobile-bottom.png' })
  await page.keyboard.press('Escape')
  await expect(editor).toBeFocused()
  await expect(last).toHaveText('First 30 paragraph')
})


test('a block handle converts every paragraph in its quote and undo restores the original container', async ({ page }) => {
  const editor = await setup(page, 'First before\n\n> Quote one\n>\n> Quote two\n\nLast after')
  await expect(editor.locator('blockquote p')).toHaveCount(2)
  await editor.locator('blockquote p').first().hover()
  await page.getByRole('button', { name: 'Block actions — drag to move' }).click()
  await page.getByRole('menuitem', { name: 'Heading 2', exact: true }).click()
  await expect(editor.locator('blockquote')).toHaveCount(0)
  await expect(editor.locator('h2')).toHaveText(['Quote one', 'Quote two'])
  await expect(editor.locator('p').first()).toHaveText('First before')
  await expect(editor.locator('p').last()).toHaveText('Last after')
  await page.keyboard.press('ControlOrMeta+Z')
  await expect(editor.locator('blockquote p')).toHaveText(['Quote one', 'Quote two'])
  await expect(editor.locator('h2')).toHaveCount(0)
})
